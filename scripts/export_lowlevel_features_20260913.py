# -*- coding: utf-8 -*-
"""导出低层参照分类器所需的特征矩阵（供第三方独立复算，无需图像、无需 GPU）。

为什么导出
----------
rocky30 第一次审核报告（T3 节）写明：本包 predictions/ 只有四类与专项两个任务的逐图
概率，"没有跨库矩阵任何一格（含 Qatar→Qatar）的逐图概率，也没有 Qatar 图像与权重"，
所以"去重后重算"与"低层探针复算"都无法执行。它列出的所需材料之一是：
**"16×16 缩略图特征或 Qatar 图像"**。

本脚本把四个队列 train/test 两个划分的
  * 16×16 灰度缩略图（256 维，按图内灰度均值缩放 /255）
  * 五个全局灰度统计（mean, SD, p5, p95, median，各 /255）
  * 标签、文件名
落成 npz，第三方可直接用 `LogisticRegression(class_weight='balanced')` 等复现
稿件里的 0.977 / 0.859 / 0.672 / 0.976（thumb16_plus_stats5，同划分同预处理）。

实现纪律：**不重写特征代码**——直接 import 已验证的 `lowlevel_same_split.gray_thumb/stats5`
与 `train_cross_cohort.build_splits`，保证与稿件数字同源。

产物：output_cross/lowlevel_features_20260913/{Cohort}_{train,test}.npz
      （thumb16, stats5, labels, filenames；外加 _INDEX.json 说明）
用法：set TBX_GRAY=1 && python export_lowlevel_features_20260913.py
"""
import os
import sys
import json
import numpy as np
from PIL import Image

assert os.environ.get("TBX_GRAY", "") == "1", "set TBX_GRAY=1 (main matrix preprocessing)"

import train_cross_cohort as T          # noqa: E402
from data_tbx11k import build_ram_cache, CACHE_SIZE, GRAYSCALE  # noqa: E402
from lowlevel_same_split import gray_thumb, stats5  # noqa: E402  复用已验证实现

COHORTS4 = ["TBX11K", "Shenzhen", "Montgomery", "Qatar"]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "output_cross", "lowlevel_features_20260913")
os.makedirs(OUT, exist_ok=True)


def readable_mask(paths):
    """复现 build_ram_cache 的可读性判定（同 open/convert/resize 操作）。"""
    ok = np.ones(len(paths), dtype=bool)
    for i, p in enumerate(paths):
        try:
            im = Image.open(p)
            im = im.convert("L").convert("RGB") if GRAYSCALE else im.convert("RGB")
            im.resize((CACHE_SIZE, CACHE_SIZE), Image.BILINEAR)
        except Exception:
            ok[i] = False
    return ok


def main():
    splits = T.build_splits(quick=False)
    assert set(splits) == set(COHORTS4), f"splits missing: {set(COHORTS4) - set(splits)}"
    index = {"note": ("features regenerated by export_lowlevel_features_20260913.py; "
                      "identical code path to lowlevel_same_split.py (gray_thumb/stats5) "
                      "and train_cross_cohort.build_splits; TBX_GRAY=1; CACHE_SIZE=%d"
                      % CACHE_SIZE),
             "scripts": {"export": "export_lowlevel_features_20260913.py",
                         "reference": "lowlevel_same_split.py",
                         "model": "train_cross_cohort.lowlevel_auc"},
             "files": {}}
    for c in COHORTS4:
        for part in ("train", "test"):
            paths, labels = splits[c][part]
            imgs, y = build_ram_cache(paths, labels)
            ok = readable_mask(paths)
            assert int(ok.sum()) == len(imgs), f"{c}/{part}: mask {int(ok.sum())} != cache {len(imgs)}"
            names = np.array([os.path.basename(p) for p, k in zip(paths, ok) if k])
            thumb = gray_thumb(imgs)
            st = stats5(imgs)
            assert thumb.shape == (len(imgs), 256) and st.shape == (len(imgs), 5)
            fn = os.path.join(OUT, f"{c}_{part}.npz")
            np.savez_compressed(fn, thumb16=thumb.astype(np.float32),
                                stats5=st.astype(np.float32),
                                labels=np.asarray(y, dtype=np.int64), filenames=names)
            index["files"][os.path.basename(fn)] = {
                "cohort": c, "split": part, "n": int(len(imgs)),
                "pos": int((np.asarray(y) == 1).sum()),
                "sha256": __import__("hashlib").sha256(open(fn, "rb").read()).hexdigest(),
            }
            print(f"[OK] {fn}  n={len(imgs)} pos={int((np.asarray(y)==1).sum())}  "
                  f"thumb={thumb.shape} stats={st.shape}", flush=True)
    with open(os.path.join(OUT, "_INDEX.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=2)
    print(f"[OK] wrote {OUT}/_INDEX.json", flush=True)


if __name__ == "__main__":
    main()
