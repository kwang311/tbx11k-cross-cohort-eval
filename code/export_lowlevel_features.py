# -*- coding: utf-8 -*-
"""Export the feature matrices needed by the low-level reference classifier (for independent third-party recomputation; no images, no GPU).

Why export
----------
The first audit report (section T3) states: this package's predictions/ holds per-image
probabilities for the four-class and the special task only, "no per-image probabilities for any cell of the cross-cohort matrix (including Qatar->Qatar), and no Qatar images or weights",
so neither the "recomputation after deduplication" nor the "low-level probe recomputation" can be carried out. One of the materials it lists as necessary is:
**"16x16 thumbnail features, or the Qatar images"**.

This script writes, for the train and test splits of the four cohorts:
  * 16x16 grayscale thumbnails (256 dims, scaled by the in-image grayscale mean, /255)
  * five global grayscale statistics (mean, SD, p5, p95, median, each /255)
  * labels and filenames
into npz files, so a third party can reproduce the 0.977 / 0.859 / 0.672 / 0.976 reported in the manuscript
(thumb16_plus_stats5, same split, same preprocessing) directly with `LogisticRegression(class_weight='balanced')` or similar.

Implementation discipline: **do not rewrite the feature code** -- import the already verified `lowlevel_same_split.gray_thumb/stats5`
and `train_cross_cohort.build_splits` directly, so the numbers share their origin with the manuscript.

Output: features/{Cohort}_{train,test}.npz
      (thumb16, stats5, labels, filenames; plus an _INDEX.json description)
Usage: set TBX_GRAY=1 && python export_lowlevel_features.py
"""
import os
import sys
import json
import numpy as np
from PIL import Image

assert os.environ.get("TBX_GRAY", "") == "1", "set TBX_GRAY=1 (main matrix preprocessing)"

import train_cross_cohort as T          # noqa: E402
from data_tbx11k import build_ram_cache, CACHE_SIZE, GRAYSCALE  # noqa: E402
from lowlevel_same_split import gray_thumb, stats5  # noqa: E402  reuse the already verified implementation

COHORTS4 = ["TBX11K", "Shenzhen", "Montgomery", "Qatar"]
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import paths as P
OUT = str(P.FEATURES)
os.makedirs(OUT, exist_ok=True)


def readable_mask(paths):
    """Reproduce the readability test of build_ram_cache (same open/convert/resize operations)."""
    ok = np.ones(len(paths), dtype=bool)
    for i, p in enumerate(paths):
        try:
            im = Image.open(p)
            im = im.convert("L").convert("RGB") if GRAYSCALE else im.convert("RGB")
            im.resize((CACHE_SIZE, CACHE_SIZE), Image.BILINEAR)
        except Exception:
            ok[i] = False
    return ok


def main():
    splits = T.build_splits(quick=False)
    assert set(splits) == set(COHORTS4), f"splits missing: {set(COHORTS4) - set(splits)}"
    index = {"note": ("features regenerated by export_lowlevel_features.py; "
                      "identical code path to lowlevel_same_split.py (gray_thumb/stats5) "
                      "and train_cross_cohort.build_splits; TBX_GRAY=1; CACHE_SIZE=%d"
                      % CACHE_SIZE),
             "scripts": {"export": "export_lowlevel_features.py",
                         "reference": "lowlevel_same_split.py",
                         "model": "train_cross_cohort.lowlevel_auc"},
             "files": {}}
    for c in COHORTS4:
        for part in ("train", "test"):
            paths, labels = splits[c][part]
            imgs, y = build_ram_cache(paths, labels)
            ok = readable_mask(paths)
            assert int(ok.sum()) == len(imgs), f"{c}/{part}: mask {int(ok.sum())} != cache {len(imgs)}"
            names = np.array([os.path.basename(p) for p, k in zip(paths, ok) if k])
            thumb = gray_thumb(imgs)
            st = stats5(imgs)
            assert thumb.shape == (len(imgs), 256) and st.shape == (len(imgs), 5)
            fn = os.path.join(OUT, f"{c}_{part}.npz")
            np.savez_compressed(fn, thumb16=thumb.astype(np.float32),
                                stats5=st.astype(np.float32),
                                labels=np.asarray(y, dtype=np.int64), filenames=names)
            index["files"][os.path.basename(fn)] = {
                "cohort": c, "split": part, "n": int(len(imgs)),
                "pos": int((np.asarray(y) == 1).sum()),
                "sha256": __import__("hashlib").sha256(open(fn, "rb").read()).hexdigest(),
            }
            print(f"[OK] {fn}  n={len(imgs)} pos={int((np.asarray(y)==1).sum())}  "
                  f"thumb={thumb.shape} stats={st.shape}", flush=True)
    with open(os.path.join(OUT, "_INDEX.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=2)
    print(f"[OK] wrote {OUT}/_INDEX.json", flush=True)


if __name__ == "__main__":
    main()
